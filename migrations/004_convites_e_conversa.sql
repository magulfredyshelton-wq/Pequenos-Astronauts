CREATE TABLE convites_conta (
    id TEXT PRIMARY KEY,
    partida TEXT NOT NULL UNIQUE REFERENCES partidas(codigo) ON DELETE CASCADE,
    destinatario TEXT NOT NULL REFERENCES contas(id) ON DELETE CASCADE,
    expira_em DOUBLE PRECISION NOT NULL
);
CREATE INDEX convites_conta_destinatario ON convites_conta(destinatario, expira_em);

CREATE TABLE mensagens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida TEXT NOT NULL,
    jogador TEXT NOT NULL,
    chave TEXT NOT NULL,
    enviada_em BIGINT NOT NULL,
    texto TEXT,
    formato TEXT,
    audio BYTEA,
    UNIQUE (partida, jogador, chave),
    FOREIGN KEY (partida, jogador) REFERENCES jogadores(partida, id) ON DELETE CASCADE,
    CHECK (
        (texto IS NOT NULL AND formato IS NULL AND audio IS NULL)
        OR (texto IS NULL AND formato IS NOT NULL AND audio IS NOT NULL)
    )
);
CREATE INDEX mensagens_partida_id ON mensagens(partida, id);

CREATE TABLE bloqueios (
    autor TEXT NOT NULL REFERENCES contas(id) ON DELETE CASCADE,
    alvo TEXT NOT NULL REFERENCES contas(id) ON DELETE CASCADE,
    PRIMARY KEY (autor, alvo),
    CHECK (autor <> alvo)
);
CREATE INDEX bloqueios_alvo ON bloqueios(alvo, autor);
CREATE TABLE denuncias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partida TEXT NOT NULL REFERENCES partidas(codigo) ON DELETE CASCADE,
    autor TEXT NOT NULL REFERENCES contas(id) ON DELETE CASCADE,
    alvo TEXT NOT NULL REFERENCES contas(id) ON DELETE CASCADE,
    mensagem BIGINT,
    motivo TEXT NOT NULL CHECK (motivo IN ('conduta', 'contacto', 'mensagem')),
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revista_em TIMESTAMPTZ
);

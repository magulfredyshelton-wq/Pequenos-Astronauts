-- Resultados do cliente 2D "sandbox". Só números e frases geradas pelo jogo, nunca texto livre do jogador.
CREATE TABLE sandbox_resultados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id TEXT NOT NULL REFERENCES contas(id) ON DELETE CASCADE,
    chave TEXT NOT NULL,
    destino TEXT NOT NULL CHECK (destino IN ('lua', 'marte')),
    resultado TEXT NOT NULL CHECK (resultado IN ('ok', 'traje', 'rad', 'ar', 'agua', 'comida')),
    estrelas SMALLINT NOT NULL CHECK (estrelas BETWEEN 0 AND 3),
    hora REAL NOT NULL CHECK (hora BETWEEN 0 AND 100),
    base_nivel SMALLINT NOT NULL CHECK (base_nivel BETWEEN 0 AND 3),
    amostras SMALLINT NOT NULL CHECK (amostras BETWEEN 0 AND 500),
    comida_produzida REAL NOT NULL DEFAULT 0 CHECK (comida_produzida BETWEEN 0 AND 100000),
    dados JSONB NOT NULL,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (conta_id, chave)
);
CREATE INDEX sandbox_resultados_conta ON sandbox_resultados(conta_id, criada_em DESC);
CREATE INDEX sandbox_resultados_ranking ON sandbox_resultados(estrelas DESC, base_nivel DESC, amostras DESC) WHERE resultado = 'ok';
